import { describe, it, expect } from "vitest";
import { isPersistentKey } from "@/lib/cache/redis";

/**
 * Что переживает пересборку образа, а что нет.
 *
 * Внешнего кеша нет, память процесса умирает вместе с контейнером, поэтому
 * список «переживающих» префиксов — единственное, что отделяет дорогие данные
 * от их повторного добывания.
 */
describe("что переживает пересборку", () => {
  it("цены игр переживают: иначе после каждой выкатки библиотека считается по средней", () => {
    // Живой случай 2026-08-12: у аккаунта со 157 играми настоящую цену получили
    // 68, остальные 67 достроены средней — бюджет походов в магазин Steam
    // потратился заново, потому что кеш цен умер вместе с контейнером.
    expect(isPersistentKey("gameprice:v1:570")).toBe(true);
    expect(isPersistentKey("storeprice:v1:ru:570")).toBe(true);
  });

  it("курс валют переживает: он общий на всех и меняется раз в день", () => {
    expect(isPersistentKey("fx:cbr:v1")).toBe(true);
  });

  it("разбор, карточка и кошелёк переживают", () => {
    for (const key of ["profile:v3:1", "portrait:v7:1:ru", "cardstats:v1:1", "rarity:v2:1", "wealth:v2:1", "art:identity:v2:1"]) {
      expect(isPersistentKey(key)).toBe(true);
    }
  });

  it("счётчики частоты и одноразовые пропуска НЕ переживают", () => {
    // Потолок на адрес обязан обнуляться вместе с процессом, а код входа —
    // одноразовый пропуск на минуты: хранить его в файле незачем и вредно.
    expect(isPersistentKey("ratelimit:1.2.3.4")).toBe(false);
    expect(isPersistentKey("logincode:123456")).toBe(false);
  });
});
