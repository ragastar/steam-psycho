/**
 * Секрет подписи подтверждений — и всё, что о нём нужно знать обеим сторонам.
 *
 * Модуль крошечный и отдельный намеренно: длину проверяют и приёмщик
 * (`stub-provider.ts`), и маршрут вебхука, а `provider.ts` сам импортирует
 * приёмщика. Держи константу в `provider.ts` — получился бы круг импортов;
 * скопируй числом — однажды разъедутся, и «проверка длины» станет проверкой
 * двух разных длин.
 */

/**
 * Короче этого секрет не принимаем. Подпись — единственное, что стоит между
 * чужим человеком и бесплатным правом, а подбирают её локально: в сеть уходит
 * один запрос на удачного кандидата. Короткий секрет — это отсутствие секрета,
 * только незаметное. Образец такой проверки — getSecret в
 * lib/identity/session.ts.
 */
export const MIN_WEBHOOK_SECRET_LENGTH = 32;

/**
 * Годный секрет или null. Читается на каждом вызове, а не при загрузке модуля:
 * иначе значение замерзало бы на том, каким было в момент первого импорта.
 */
export function readWebhookSecret(): string | null {
  const secret = process.env.PAYMENT_WEBHOOK_SECRET;
  if (!secret || secret.length < MIN_WEBHOOK_SECRET_LENGTH) return null;
  return secret;
}
