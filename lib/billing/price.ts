/**
 * Цена полного разбора.
 *
 * Отдельный крошечный модуль, потому что цена нужна с обеих сторон: серверу —
 * чтобы завести заказ в копейках, витрине — чтобы показать рубли. Из файла
 * маршрута её экспортировать нельзя (оттуда экспортируются только обработчик и
 * `runtime`), а тянуть в браузер `lib/billing/store` вместе с базой — тем
 * более. Здесь нет ни одного импорта, поэтому модуль безопасно уезжает в
 * клиентский компонент.
 *
 * Хранится в копейках: деньги дробями считать нельзя, а эквайеры принимают
 * сумму именно в наименьшей единице.
 */
export const PRICE_KOP = 19900;

export const CURRENCY = "RUB";

/**
 * Копейки → рубли для показа человеку. Сегодняшняя цена целая (199 ₽), и
 * дробную часть в этом случае не показываем: «199 ₽» читается, «199.00 ₽»
 * выглядит как ошибка вёрстки. Разделитель дробной части — точка, а не
 * запятая: до первой некруглой цены этой строки не увидит никто, а угадывать
 * правила языка тут незачем — знак валюты и так живёт в переводе.
 */
export function priceInRubles(amountKop: number = PRICE_KOP): string {
  return amountKop % 100 === 0 ? String(amountKop / 100) : (amountKop / 100).toFixed(2);
}
