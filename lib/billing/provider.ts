import { paywallMode } from "@/lib/access/entitlement";
import { getStubProvider } from "./stub-provider";

/**
 * Приёмщик оплаты. Форма интерфейса намеренно повторяет ЮКассу — редирект на
 * страницу оплаты плюс вебхук с подтверждением, — потому что почти все
 * российские эквайеры устроены так же: подмена заглушки на боевую кассу будет
 * дешёвой, а остальной код о разнице знать не должен.
 */
/**
 * Что именно сообщила касса. Приход подтверждения сам по себе НЕ означает
 * «оплачено»: тем же вебхуком касса сообщает и об отказе банка. И сумму она
 * присылает фактическую — сверять её с заказом обязан тот, кто выдаёт право,
 * иначе подтверждение об уплате одной копейки откроет разбор за 199 рублей.
 */
export interface VerifiedPayment {
  orderId: number;
  providerOrderId: string;
  outcome: "paid" | "declined";
  /** Сколько РЕАЛЬНО уплачено. Сверяется с orders.amount_kop. */
  amountKop: number;
  /** Валюта фактического платежа: 19900 тугриков — не 19900 копеек. */
  currency: string;
}

export interface PaymentProvider {
  /** Пишется в заказ: поддельные заказы не должны смешаться с настоящими. */
  name: string;
  createPayment(o: {
    orderId: number;
    amountKop: number;
    locale: string;
  }): Promise<{ payUrl: string; providerOrderId: string }>;
  /**
   * Проверяет подтверждение от кассы. `rawBody` — СЫРОЕ тело запроса: подпись
   * считается по байтам, а не по разобранному и заново собранному JSON.
   * Любая осечка — null, то есть отказ.
   */
  verifyWebhook(rawBody: string, signature: string | null): VerifiedPayment | null;
}

/**
 * Короче этого секрет не принимаем. Подпись — единственное, что стоит между
 * чужим человеком и бесплатным правом, а подбирают её локально: в сеть уходит
 * один запрос на удачного кандидата. Короткий секрет — это отсутствие секрета,
 * только незаметное. Образец такой проверки — getSecret в
 * lib/identity/session.ts.
 */
export const MIN_WEBHOOK_SECRET_LENGTH = 32;

/**
 * Заголовок, в котором касса присылает подпись. Живёт здесь, а не в файле
 * маршрута: оттуда экспортировать можно только обработчик и runtime, а имя
 * нужно ещё и тому, кто вебхук отправляет (страница поддельной кассы).
 */
export const PAYMENT_SIGNATURE_HEADER = "x-payment-signature";

/**
 * Кто сейчас принимает деньги. null — «касса не работает»: не выключенная
 * витрина, а именно отсутствие приёмщика.
 *
 * Положение переключателя читает `paywallMode` — тот же самый разбор
 * `PAYWALL_MODE`, что решает и вопрос доступа. Именно один разбор, а не два
 * похожих: разъехавшись, они дали бы состояние «касса берёт деньги, но доступ
 * открыт всем» или наоборот.
 */
export function getProvider(): PaymentProvider | null {
  const mode = paywallMode();

  if (mode === "stub") return getStubProvider();

  if (mode === "live") {
    console.error("[billing] PAYWALL_MODE=live, но ЮКасса не подключена — приём оплат отключён");
    return null;
  }

  return null;
}
