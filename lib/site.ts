/**
 * Единственный источник правды по адресу сайта.
 *
 * Домен переезжал (gamertype.fun → zadrotometr.ru), и выяснилось, что он был
 * вписан руками сразу в четырёх местах: подпись на самой карточке, подпись на
 * превью для соцсетей и дважды в приветствии бота. Переезд их не затронул, и
 * сайт продолжал рекламировать мёртвый адрес — причём на той самой картинке,
 * которой делятся.
 *
 * ВАЖНО: значение вшивается при СБОРКЕ. Переменные с префиксом NEXT_PUBLIC_
 * Next подставляет прямо в код, а не читает во время работы, поэтому строка в
 * .env.local на готовый образ уже не влияет — менять надо аргумент сборки
 * NEXT_PUBLIC_BASE_URL в docker-compose.override.yml.
 */
export const SITE_URL = process.env.NEXT_PUBLIC_BASE_URL || "https://zadrotometr.ru";

/** Домен без протокола и хвостового слэша — для подписей и текстов бота. */
export function siteHost(url: string): string {
  return url.replace(/^https?:\/\//, "").replace(/\/+$/, "");
}

export const SITE_HOST = siteHost(SITE_URL);
